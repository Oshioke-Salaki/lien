// The whole life of a loan on a live network: real contracts, real OutLayer TEE
// workers, real chain time. Every step asserts what happened and is written to
// docs/evidence with its transaction, so the result can be checked independently.
//
//   LIEN_NETWORK=testnet ROLES=operator,alice,bob,customer,bidder npm run e2e

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { account, call, explorerTx, loadDeployment, network, OUTLAYER_API, pay, refused, ROOT, sentinelService, sleep, USD, view } from "./lib.js";

const net = network();
const d = loadDeployment(net);
const [operatorId, aliceId, bobId, customerId, bidderId] = (process.env.ROLES ?? "").split(",");
if (!operatorId || !aliceId || !bobId || !customerId || !bidderId) {
  throw new Error("Set ROLES=operator,alice,bob,customer,bidder");
}
const [operator, alice, bob, customer, bidder] = [operatorId, aliceId, bobId, customerId, bidderId].map((id) => account(id, net)) as [
  ReturnType<typeof account>, ReturnType<typeof account>, ReturnType<typeof account>, ReturnType<typeof account>, ReturnType<typeof account>,
];

const label = process.env.LABEL ?? `e2e-${Math.floor(Date.now() / 1000) % 100000}`;
const agent = `${label}.${d.registry}`;
const collector = `${label}-in.${d.registry}`;

const lines: string[] = [];
const log = (text: string) => {
  console.log(text);
  lines.push(text);
};
function step(title: string, tx?: string) {
  log(`- **${title}**${tx ? ` ([tx](${explorerTx(tx, net)}))` : ""}`);
}
function check(ok: boolean, what: string, detail: unknown = "") {
  if (!ok) throw new Error(`CHECK FAILED: ${what} ${JSON.stringify(detail)}`);
  log(`  - ok: ${what}`);
}

const state = () => view<any>(agent, "get_agent", {}, net);
const balance = async (id: string) => BigInt(await view<string>(d.token, "ft_balance_of", { account_id: id }, net));

/** Waits for a job to settle, since OutLayer resolves it a few seconds later. */
async function settled(jobId: number) {
  for (let i = 0; i < 40; i += 1) {
    const job = await view<any>(agent, "get_job", { job_id: jobId }, net);
    if (job && job.status !== "Pending") return job;
    await sleep(3_000);
  }
  throw new Error(`job ${jobId} never settled`);
}

async function until(unixSeconds: number) {
  for (;;) {
    const now = (await state()).now as number;
    if (now >= unixSeconds) return;
    await sleep(Math.min(5, unixSeconds - now) * 1000);
  }
}

log(`# Live end-to-end run on ${net}\n`);
log(`Generated by \`ops/src/e2e.ts\` on ${new Date().toISOString()}. Agent build \`${d.sentinel?.hash}\`.\n`);

// Everyone needs a token account and test funds.
for (const person of [operator, alice, bob, customer, bidder]) {
  await call(alice, d.token, "storage_deposit", { account_id: person.accountId }, { deposit: 1_250_000_000_000_000_000_000n, tgas: 30n });
  if (net === "testnet") await call(alice, d.token, "faucet", { account_id: person.accountId, amount: (50n * USD).toString() }, { tgas: 30n });
}

if (d.sentinel?.vendor) {
  await call(alice, d.token, "storage_deposit", { account_id: d.sentinel.vendor }, { deposit: 1_250_000_000_000_000_000_000n, tgas: 30n });
}

log("## A business is created\n");
const created = await call(
  operator,
  d.registry,
  "create_agent",
  {
    label,
    name: "Sentinel",
    description: "Checks a NEAR account before an agent pays or signs.",
    source_url: "https://github.com/Oshioke-Salaki/lien",
    service: sentinelService(d),
  },
  { deposit: 10n ** 24n, tgas: 300n },
);
step(`Created ${agent}`, created.tx);
const keys = (await operator.provider.viewAccessKeyList({ accountId: agent })).keys;
check(keys.length === 0, "the business account has zero access keys");
const collectorKeys = (await operator.provider.viewAccessKeyList({ accountId: collector })).keys;
check(collectorKeys.length === 0, "its inbox has zero access keys");

log("\n## Lenders fund a loan\n");
const offered = await call<number>(operator, agent, "create_offer", {
  terms: {
    principal: (5n * USD).toString(),
    total_due: (5n * USD + USD / 2n).toString(),
    lender_bps: 5_000,
    operator_bps: 1_000,
    funding_secs: 3_600,
    term_secs: 86_400,
    window_secs: 60,
    min_payment_per_window: (2n * USD).toString(),
    grace_secs: 20,
    auction_secs: 40,
    auction_reserve_bps: 2_000,
  },
});
step("Operator offered 5 tUSD, repaying 5.5", offered.tx);
const funded1 = await pay(alice, d.token, agent, 3n * USD, { action: "fund", loan_id: 0 });
const funded2 = await pay(bob, d.token, agent, 2n * USD, { action: "fund", loan_id: 0 });
step("Alice lent 3", funded1.tx);
step("Bob lent 2", funded2.tx);
let s = await state();
check(s.current_loan.status === "Active", "the loan activated once fully funded");
check(s.ledger.opex === (5n * USD).toString(), "the principal is working capital");

log("\n## The operator tries to take the money\n");
for (const [method, args] of [
  ["withdraw_opex", { amount: "1" }],
  ["update_service", { service: sentinelService(d) }],
  ["create_offer", { terms: s.current_loan.terms }],
] as const) {
  const reason = await refused(operator, agent, method, args);
  check(reason.includes("while a loan is open"), `${method} refused`);
}

log("\n## A customer buys real work from the TEE\n");
const before = await balance(customerId);
const paid = await pay(customer, d.token, agent, USD / 4n, { action: "job", input: `is ${d.registry} safe?` });
step("Customer paid 0.25 for a check", paid.tx);
const job0 = await settled(0);
check(job0.status === "Done", "OutLayer ran the pinned build and the job settled", job0);
log(`  - report: \`${job0.report}\``);
check(JSON.parse(job0.report).target === d.registry, "the report is about the requested account");
check((await balance(customerId)) === before - USD / 4n, "the customer paid exactly the price");
s = await state();
check(s.current_loan.repaid === (USD / 8n).toString(), "half of the revenue went to lenders");
check(s.stats.spent === "20000" && s.stats.spends_blocked === 0, "the agent paid its approved data vendor, inside the policy");

const attestation = await (await fetch(`${OUTLAYER_API[net]}/attestations/by-tx/${paid.tx}`)).json().catch(() => null) as any;
if (attestation?.tdx_quote) {
  check(attestation.executed_wasm_sha256 === d.sentinel?.hash, "the Intel TDX attestation names the exact pinned build");
  log(`  - attestation request ${attestation.request_id}, quote ${attestation.tdx_quote.length} chars, [view](${OUTLAYER_API[net]}/attestations/by-tx/${paid.tx})`);
} else {
  log("  - attestation not indexed yet at the time of this check");
}

log("\n## Income from outside comes through the inbox\n");
const sent = await call(customer, d.token, "ft_transfer", { receiver_id: collector, amount: (USD / 2n).toString() }, { deposit: 1n, tgas: 30n });
step("A plain transfer of 0.5 to the inbox, the way a NEAR Intents payout arrives", sent.tx);
const forwarded = await call(bob, collector, "forward");
step("Anyone forwards it into the waterfall", forwarded.tx);
s = await state();
check(s.stats.external_revenue === (USD / 2n).toString(), "it was recorded as revenue");
check(s.current_loan.repaid === (USD / 8n + USD / 4n).toString(), "lenders received their half");

log("\n## The business stops paying\n");
const foreclosableAt = s.current_loan.foreclosable_at as number;
const early = await refused(bidder, agent, "foreclose");
check(early.includes("grace"), "foreclosure is refused before the grace period ends");
await until(foreclosableAt);
const closed = await call(bidder, agent, "foreclose");
step("A stranger foreclosed. No keeper, no admin.", closed.tx);
s = await state();
check(s.current_loan.status === "Foreclosed", "the loan is in foreclosure");

const locked = await refused(operator, agent, "withdraw_operator");
check(locked.includes("locked") || locked.includes("nothing"), "the operator is locked out");

log("\n## The business keeps earning, now for lenders\n");
const repaidBefore = BigInt(s.current_loan.repaid);
const paid2 = await pay(customer, d.token, agent, USD / 4n, { action: "job", input: "check near" });
step("Another customer job, after foreclosure", paid2.tx);
const job1 = await settled(1);
check(job1.status === "Done", "the same address served the customer without interruption", job1);
s = await state();
check(BigInt(s.current_loan.repaid) === repaidBefore + (USD / 4n) * 6000n / 10000n, "the operator's share now goes to lenders too");

log("\n## The business is sold\n");
const bid = await pay(bidder, d.token, agent, 3n * USD, { action: "bid" });
step("A buyer bid 3", bid.tx);
s = await state();
await until(s.current_loan.auction.ends_at);
const operatorBefore = await balance(operatorId);
const sold = await call(alice, agent, "settle_auction");
step("Anyone settled the sale", sold.tx);
s = await state();
check(s.operator === bidderId, "the buyer now operates the business");
check(s.current_loan === null, "the debt is closed");
const loan = await view<any>(agent, "get_loan", { loan_id: 0 }, net);
check(loan.status === "Sold", "the loan is recorded as sold");
const outstandingPaid = BigInt(loan.repaid);
check(outstandingPaid <= 5n * USD + USD / 2n, "lenders never receive more than they were owed");
log(`  - lenders recovered ${Number(outstandingPaid) / 1e6} of 5.5 owed; former operator received ${Number((await balance(operatorId)) - operatorBefore) / 1e6} surplus`);

log("\n## The new owner is in control, and lenders collect\n");
const changed = await call(bidder, agent, "update_service", { service: sentinelService(d, { price: (USD / 2n).toString() }) });
step("The buyer changed the price", changed.tx);
const denied = await refused(operator, agent, "update_service", { service: sentinelService(d) });
check(denied.includes("only the operator"), "the former operator has no control");
const aliceBefore = await balance(aliceId);
const claimA = await call<string>(alice, agent, "claim", { loan_id: 0 });
const claimB = await call<string>(bob, agent, "claim", { loan_id: 0 });
step("Alice claimed", claimA.tx);
step("Bob claimed", claimB.tx);
check((await balance(aliceId)) - aliceBefore === BigInt(claimA.result), "Alice received exactly the amount claimed");

const ledger = (await state()).ledger as Record<string, string>;
const owed = Object.values(ledger).reduce((sum, v) => sum + BigInt(v), 0n);
const held = await balance(agent);
check(held >= owed, "the contract holds at least what its ledger says", { held: String(held), owed: String(owed) });
log(`\nAll checks passed. Ledger ${owed}, held ${held}.`);

const dir = join(ROOT, "docs/evidence");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, `${net}-e2e.md`), `${lines.join("\n")}\n`);
