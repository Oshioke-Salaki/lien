import { chromium } from "@playwright/test";
const D = "/private/tmp/claude-501/-Users-macbookpro-Desktop-near/f7214798-7f83-4ad2-bfeb-482bbe49607c/scratchpad/audit3/";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const errs = [];
p.on("console", m => { if (m.type()==="error"||m.type()==="warning") errs.push(m.type()+": "+m.text().slice(0,200)); });
p.on("requestfailed", r => errs.push("FAILED "+r.url()+" "+r.failure()?.errorText));
p.on("response", r => { if (r.status()>=400) errs.push("HTTP "+r.status()+" "+r.url()); });
const t0 = Date.now();
await p.goto(process.argv[2] || "https://lien-five.vercel.app", { waitUntil: "domcontentloaded" });
console.log("DCL ms", Date.now()-t0);
const fcp = await p.evaluate(() => performance.getEntriesByName("first-contentful-paint")[0]?.startTime);
console.log("FCP", fcp);
await p.waitForTimeout(7000);
await p.screenshot({ path: D+"shots/"+(process.argv[3]||"home")+".png", fullPage: true });
console.log((await p.innerText("body")).slice(0, 12000));
const links = await p.$$eval("a", as => as.map(a => a.innerText.trim().slice(0,40)+" -> "+a.getAttribute("href")));
console.log("LINKS", links.join("\n"));
const btns = await p.$$eval("button", as => as.map(a => a.innerText.trim().slice(0,50)));
console.log("BUTTONS", btns.join(" | "));
console.log("ERRS", errs.join("\n"));
await b.close();
